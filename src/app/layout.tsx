import type { Metadata, Viewport } from "next";
import { Bricolage_Grotesque, JetBrains_Mono, Newsreader } from "next/font/google";
import { SiteFooter, SiteHeader } from "@/components/chrome";
import { CursorLight } from "@/components/cursor-light";
import { Intro, IntroBoot } from "@/components/intro";
import { ParticleBrainMount } from "@/components/particle-brain-mount";
import { ProximityMount } from "@/components/proximity-mount";
import { Reveal } from "@/components/reveal";
import { RoomWatcher } from "@/components/room-watcher";
import { wall } from "@/lib/colours";
import { ogImageUrl } from "@/lib/metadata";
import { siteDescription, siteTitle, siteUrl } from "@/lib/site";
import "./globals.css";

/* Three families, and each has one job.

   Bricolage Grotesque is the voice of the page: the name, every heading, the
   labels and the paragraphs. It is a variable face with a weight axis from 200
   to 800 and a width axis from 75 to 100, which is what the letter weight
   effect needs in order to be a real change of weight and not a smear, and its
   optical size axis keeps the small type as clean as the large.

   Newsreader is for what is read slowly: the essays, and the letter in the
   about section. A serif with an optical size axis, and an italic that is
   drawn and not slanted.

   JetBrains Mono is for what is a listing or a clock: a stack, a figure in a
   table, a line of code.

   No weight arrays, which gets each as a variable font: one file covering the
   whole axis rather than a static face per weight. The stand-ins for each while
   it arrives are generated by next/font from the real faces' metrics, which it
   has for all three, and tests/performance.spec.ts holds the page to a shift of
   under 0.01 when they land late. */
const bricolage = Bricolage_Grotesque({
  variable: "--font-bricolage",
  subsets: ["latin"],
  display: "swap",
  axes: ["opsz", "wdth"],
});

const newsreader = Newsreader({
  variable: "--font-newsreader",
  subsets: ["latin"],
  display: "swap",
  style: ["normal", "italic"],
  axes: ["opsz"],
});

/* Not preloaded. It is for a line of code in an essay and nothing on the home
   page is set in it, so a preload would have every page fetch a font that most
   of them never draw. The browser still fetches it the moment something is. */
const jetbrains = JetBrains_Mono({
  variable: "--font-jetbrains",
  subsets: ["latin"],
  display: "swap",
  preload: false,
});

/* Metadata merges per key, not per field: a page that declares openGraph
   replaces this whole object and loses the site-wide values, and declaring it
   at all suppresses any file-convention opengraph-image. Every page therefore
   builds its tags through buildMetadata() in @/lib/metadata, which always
   emits a complete openGraph including an explicit image. */
export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: {
    default: siteTitle,
    template: `%s · ${siteTitle}`,
  },
  description: siteDescription,
  alternates: {
    canonical: "/",
    types: { "application/atom+xml": `${siteUrl}/feed.xml` },
  },
  openGraph: {
    type: "website",
    siteName: siteTitle,
    title: siteTitle,
    description: siteDescription,
    url: siteUrl,
    images: [
      { url: ogImageUrl("/"), width: 1200, height: 630, alt: siteTitle },
    ],
  },
  twitter: {
    card: "summary_large_image",
    title: siteTitle,
    description: siteDescription,
    images: [ogImageUrl("/")],
  },
};

/* The wall of the first room, because every page starts in it and the browser's
   own chrome should meet it rather than flash another colour above it. The
   room watcher moves the theme colour with the wall as the page changes rooms. */
export const viewport: Viewport = {
  themeColor: wall,
  colorScheme: "dark",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en-GB"
      data-room="midnight"
      className={`${bricolage.variable} ${newsreader.variable} ${jetbrains.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        {/* First thing in the document, so the decision about the opening
            animation is made before anything paints. It sets one attribute.
            See the note in components/intro.tsx. */}
        <IntroBoot />

        {/* Says scripts are running, before anything paints, so the stylesheet
            only puts things where they arrive from when something is going to
            bring them. See the note on data-reveal in globals.css. */}
        <script dangerouslySetInnerHTML={{ __html: 'document.documentElement.dataset.js="1"' }} />

        {/* The cloud has no layer of its own to sit on. The wall is painted on
            the root element, the canvas is fixed behind everything at a
            negative z-index, and every block in the page is transparent, so
            the cloud shows through to the wall and never over a word. That is
            a rule about the whole page: nothing between the root and the
            content may paint an opaque background, or the cloud is covered.

            It is kept off the words by the final pass cutting it to the space
            the layout leaves for it, not by being dimmed. It mounts itself only
            on the home page. */}
        <ParticleBrainMount />

        {/* First focusable element on the page. Visually hidden until it takes
            focus, so a keyboard user can reach the content without tabbing
            through the whole header on every navigation. */}
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:absolute focus:top-3 focus:left-3 focus:z-70 focus:border-2 focus:border-carbon focus:bg-chalk focus:px-4 focus:py-2.5 focus:t-label focus:text-carbon"
        >
          Skip to content
        </a>
        <SiteHeader />
        <main id="main" tabIndex={-1} className="flex-1 outline-none">
          <CursorLight />
          {children}
        </main>
        <SiteFooter />
        <Intro />
        <ProximityMount />
        {/* The weather: moves the page from room to room as the cloud changes
            shape. Renders nothing. */}
        <RoomWatcher />
        <Reveal />
        {/* Static and deferred rather than a React component, so a page view
            is recorded as soon as the document is parsed instead of waiting
            for hydration. See the note at the top of the file. */}
        <script defer src="/analytics.js" />
      </body>
    </html>
  );
}
